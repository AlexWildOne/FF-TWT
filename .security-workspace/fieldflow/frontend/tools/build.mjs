if (!compiled.includes(version) || !compiled.includes(contract) || !compiled.includes(typedOfflineContract) || !compiled.includes(typedDraftContract) || !compiled.includes(typedFormContract) || !compiled.includes(typedSubmissionContract) || !compiled.includes(canonicalAnswerSemanticsContract) || !compiled.includes('source: \'typescript\'')) {
  throw new Error('Compiled frontend bundle failed identity verification');
}

const banner = `/* FieldFlow ${version} | TypeScript frontend foundation | ${contract} | ${typedOfflineContract} | ${typedDraftContract} | ${typedFormContract} | ${typedSubmissionContract} | ${canonicalAnswerSemanticsContract} | ${typedSpecializedValidationContract} */\n`;
const wrapped = `${banner}(function(){\n'use strict';\n${compiled}\n})();\n`;
const destination = path.join(pluginDir, 'assets', `fieldflow-frontend-core-${version}.js`);
fs.writeFileSync(destination, wrapped, 'utf8');

const reactBackofficeContract = 'fieldflow-react-backoffice-foundation-v1';
const reactSharedContract = 'fieldflow-react-backoffice-shared-v1';
const reactAnalyticsContract = 'fieldflow-react-analytics-foundation-v1';
const reactTempFile = path.join(tempDir, 'fieldflow-react-backoffice.js');
const reactResult = spawnSync(tsc, ['-p', path.join(frontendDir, 'tsconfig.react-backoffice.json'), '--outFile', reactTempFile], {
  cwd: frontendDir,
  encoding: 'utf8',
  stdio: 'pipe'
});
if (reactResult.status !== 0) {
  process.stderr.write(reactResult.stdout || '');
  process.stderr.write(reactResult.stderr || '');
  process.exit(reactResult.status || 1);
}
const reactCompiled = fs.readFileSync(reactTempFile, 'utf8');
if (!reactCompiled.includes(version) || !reactCompiled.includes(reactBackofficeContract) || !reactCompiled.includes(reactSharedContract) || !reactCompiled.includes(reactAnalyticsContract) || !reactCompiled.includes('mobile-release-status') || !reactCompiled.includes('device-control-table') || !reactCompiled.includes('analytics-context-kpis') || !reactCompiled.includes('fieldflow_react_devices_list') || !reactCompiled.includes('fieldflow_react_device_action') || !reactCompiled.includes('FieldFlowAnalytics2') || !reactCompiled.includes('wordpress-wp-element')) {
  throw new Error('Compiled React backoffice bundle failed identity verification');
}
const reactBanner = `/* FieldFlow ${version} | React Backoffice Foundation | ${reactBackofficeContract} | ${reactSharedContract} | ${reactAnalyticsContract} | WordPress wp-element */\n`;
const reactWrapped = `${reactBanner}(function(){\n'use strict';\n${reactCompiled}\n})();\n`;
const reactDestination = path.join(pluginDir, 'assets', `fieldflow-react-backoffice-${version}.js`);
fs.writeFileSync(reactDestination, reactWrapped, 'utf8');


const reactFrontContract = 'fieldflow-react-front-foundation-v1';
const modernizationClosureContract = 'fieldflow-modernization-stable-closure-v1';
