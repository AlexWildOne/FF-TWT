if (reactFrontResult.status !== 0) {
  process.stderr.write(reactFrontResult.stdout || '');
  process.stderr.write(reactFrontResult.stderr || '');
  process.exit(reactFrontResult.status || 1);
}
const reactFrontCompiled = fs.readFileSync(reactFrontTempFile, 'utf8');
if (!reactFrontCompiled.includes(version) || !reactFrontCompiled.includes(modernizationClosureContract) || !reactFrontCompiled.includes(reactFrontContract) || !reactFrontCompiled.includes(reactFormWizardContract) || !reactFrontCompiled.includes(reactOperationalShellContract) || !reactFrontCompiled.includes(reactOperationalModulesContract) || !reactFrontCompiled.includes(operationalModernizationContract) || !reactFrontCompiled.includes(operationalModernizationWave2Contract) || !reactFrontCompiled.includes('react-event-shell-9o') || !reactFrontCompiled.includes('react-event-shell-9q') || !reactFrontCompiled.includes(reactMyRouteContract) || !reactFrontCompiled.includes(reactSimpleFieldContract) || !reactFrontCompiled.includes(reactSimpleFieldControlContract) || !reactFrontCompiled.includes(reactChoiceFieldContract) || !reactFrontCompiled.includes(reactSpecialFieldContract) || !reactFrontCompiled.includes(reactMediaControlContract) || !reactFrontCompiled.includes(reactFormCompletionContract) || !reactFrontCompiled.includes(frontTransitionStabilityContract) || !reactFrontCompiled.includes(reactClientWave1Contract) || !reactFrontCompiled.includes(reactClientWave2Contract) || !reactFrontCompiled.includes(crossPortalIsolationContract) || !reactFrontCompiled.includes(clientPanelLifecycleContract) || !reactFrontCompiled.includes(reactLocaleSwitcherContract) || !reactFrontCompiled.includes(localeBrandScopeContract) || !reactFrontCompiled.includes(appShellLocaleContract) || !reactFrontCompiled.includes(browserlikeTranslationContract) || !reactFrontCompiled.includes('fieldFlowReactLocaleSwitcherComponent') || !reactFrontCompiled.includes('Invalid hook call') || !reactFrontCompiled.includes('typescript-react-wp-element') || !reactFrontCompiled.includes('data-client-wave1') || !reactFrontCompiled.includes('data-client-wave2') || !reactFrontCompiled.includes('data-portal-scope') || !reactFrontCompiled.includes('form-wizard-progress') || !reactFrontCompiled.includes('operational-shell') || !reactFrontCompiled.includes('operational-module-controls') || !reactFrontCompiled.includes('data-fieldflow-react-operational-native') || !reactFrontCompiled.includes('my-route-toolbar') || !reactFrontCompiled.includes('simple-field-assist') || !reactFrontCompiled.includes('choice-field-control') || !reactFrontCompiled.includes('special-field-assist') || !reactFrontCompiled.includes('wordpress-wp-element')) {
  throw new Error('Compiled React front bundle failed identity verification');
}
const reactFrontBanner = `/* FieldFlow ${version} | React Front Foundation | ${reactFrontContract} | ${reactFormWizardContract} | ${reactOperationalShellContract} | ${reactOperationalModulesContract} | ${operationalModernizationContract} | ${operationalModernizationWave2Contract} | ${reactMyRouteContract} | ${reactSimpleFieldContract} | ${reactSimpleFieldControlContract} | ${reactChoiceFieldContract} | ${reactSpecialFieldContract} | ${reactMediaControlContract} | ${reactFormCompletionContract} | ${frontTransitionStabilityContract} | ${reactClientWave1Contract} | ${reactClientWave2Contract} | ${crossPortalIsolationContract} | ${clientPanelLifecycleContract} | ${reactLocaleSwitcherContract} | ${localeBrandScopeContract} | ${appShellLocaleContract} | ${browserlikeTranslationContract} | Modernization Stable Closure | ${modernizationClosureContract} | WordPress wp-element */\n`;
const reactFrontWrapped = `${reactFrontBanner}(function(){\n'use strict';\n${reactFrontCompiled}\n})();\n`;
const reactFrontDestination = path.join(pluginDir, 'assets', `fieldflow-react-front-${version}.js`);
fs.writeFileSync(reactFrontDestination, reactFrontWrapped, 'utf8');

fs.rmSync(tempDir, { recursive: true, force: true });
process.stdout.write(`Built ${path.relative(pluginDir, destination)}\n`);
process.stdout.write(`Built ${path.relative(pluginDir, reactDestination)}\n`);
process.stdout.write(`Built ${path.relative(pluginDir, reactFrontDestination)}\n`);
