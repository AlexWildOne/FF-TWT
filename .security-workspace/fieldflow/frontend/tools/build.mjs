import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const toolDir = path.dirname(fileURLToPath(import.meta.url));
const frontendDir = path.resolve(toolDir, '..');
const pluginDir = path.resolve(frontendDir, '..');
const pluginFile = path.join(pluginDir, 'fieldflow.php');
const generatedFile = path.join(frontendDir, 'src', 'version.generated.ts');
const tempDir = path.join(frontendDir, '.build');
const tempFile = path.join(tempDir, 'fieldflow-frontend-core.js');

const plugin = fs.readFileSync(pluginFile, 'utf8');
const versionMatch = plugin.match(/define\(\s*['"]FIELDFLOW_VERSION['"]\s*,\s*['"]([^'"]+)['"]\s*\)/);
if (!versionMatch) throw new Error('FIELDFLOW_VERSION not found in fieldflow.php');
const version = versionMatch[1];
if (!/^\d+\.\d+\.\d+(?:\.\d+)?$/.test(version)) throw new Error(`Unsupported FieldFlow version: ${version}`);

fs.writeFileSync(
  generatedFile,
  `// Generated by frontend/tools/build.mjs from fieldflow.php. Do not edit manually.\nconst FIELD_FLOW_FRONTEND_BUILD_VERSION = '${version}';\n`,
  'utf8'
);
fs.mkdirSync(tempDir, { recursive: true });

const localTsc = process.platform === 'win32'
  ? path.join(frontendDir, 'node_modules', '.bin', 'tsc.cmd')
  : path.join(frontendDir, 'node_modules', '.bin', 'tsc');
const tsc = fs.existsSync(localTsc) ? localTsc : 'tsc';
const result = spawnSync(tsc, ['-p', path.join(frontendDir, 'tsconfig.json'), '--outFile', tempFile], {
  cwd: frontendDir,
  encoding: 'utf8',
  stdio: 'pipe'
});
if (result.status !== 0) {
  process.stderr.write(result.stdout || '');
  process.stderr.write(result.stderr || '');
  process.exit(result.status || 1);
}

const compiled = fs.readFileSync(tempFile, 'utf8');
const contract = 'fieldflow-frontend-build-foundation-v1';
const typedOfflineContract = 'fieldflow-typed-offline-core-v1';
const typedDraftContract = 'fieldflow-typed-draft-media-core-v1';
