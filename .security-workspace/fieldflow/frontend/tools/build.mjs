const reactSimpleFieldControlContract = 'fieldflow-react-simple-field-control-v1';
const reactChoiceFieldContract = 'fieldflow-react-choice-field-control-v1';
const reactSpecialFieldContract = 'fieldflow-react-special-field-assist-v1';
const reactMediaControlContract = 'fieldflow-react-media-control-v1';
const reactFormCompletionContract = 'fieldflow-react-form-completion-v1';
const frontTransitionStabilityContract = 'fieldflow-front-transition-stability-v1';
