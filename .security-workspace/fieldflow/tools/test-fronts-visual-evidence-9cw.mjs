import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
const root = path.resolve(import.meta.dirname,'..');
const php = fs.readFileSync(path.join(root,'src/Forms/FormRenderer.php'),'utf8');
const a = php.indexOf("return <<<'JS'");
const b = php.indexOf('\nJS;',a);
assert(a>=0&&b>a);
const js = php.slice(a+"return <<<'JS'".length,b);
new vm.Script(js);
assert(js.includes('function rpVisionReviewMessage(it)'));
assert(js.includes('rpVisionReviewMessage(it)'));
assert(js.includes('it.needs_review||it.fronts===null'));
assert(js.includes('data-vision-fill'),'explicit confirmation required');
assert(!js.includes('function rpVisionAutoConfirm'),'no unattended confirmation');
const fn=js.slice(js.indexOf('  function rpVisionReviewMessage('),js.indexOf('  function rpVisionRenderResult('));
const ctx=vm.createContext({});
vm.runInContext(fn,ctx);
assert.match(ctx.rpVisionReviewMessage({review_reason:'duplicate_position'}),/duplicação/i);
assert.match(ctx.rpVisionReviewMessage({review_reason:'variant_unverified'}),/Variante não comprovada/i);
assert.match(ctx.rpVisionReviewMessage({review_reason:'brand_unverified'}),/Marca não comprovada/i);
assert.match(ctx.rpVisionReviewMessage({review_reason:'no_visual_proof'}),/prova visual/i);
const service=fs.readFileSync(path.join(root,'src/Vision/FrontsVisionService.php'),'utf8');
assert(service.includes("VISUAL_EVIDENCE_CONTRACT = 'fieldflow-fronts-visual-evidence-9cw-v1'"));
assert(service.includes("$prompt = self::blindInventoryPrompt();"));
assert(service.includes("$result = self::parseBlindInventory($raw, $items);"));
assert(service.includes("'max_attempts' => 1"));
assert(service.includes("'disable_model_fallback' => true"));
console.log('FRONTS VISUAL EVIDENCE 9CW JS OK | per-SKU uncertainty | no auto-fill | Azure boxes | one paid request');
