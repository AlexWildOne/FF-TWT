import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
const root=path.resolve(import.meta.dirname,'..');
const source=fs.readFileSync(path.join(root,'src/Forms/FormRenderer.php'),'utf8');
const a=source.indexOf("return <<<'JS'");
const b=source.indexOf('\nJS;',a);
assert(a>=0 && b>a,'Inline camera script missing');
const js=source.slice(a+"return <<<'JS'".length,b);
new vm.Script(js);
assert(js.includes('rpVisionEsc(cameraReason)'), 'escaped reason');
assert(js.includes('st.blockReason'), 'server-side reason forwarded');
assert(js.includes('navigator.onLine===false?'), 'network distinction');
assert(js.includes("$field.attr('data-vision-block-reason')"),'camera reason present in both entrypoints');
assert.equal(js.split("$field.attr('data-vision-block-reason')").length-1,2,'two entrypoints');
assert(!js.includes('Câmara com IA indisponível, sem rede ou orçamento não autorizado'),'no ambiguous notice');
const php=fs.readFileSync(path.join(root,'src/Forms/FormRenderer.php'),'utf8');
assert(php.includes('data-vision-block-reason'), 'server markup reason');
console.log('FRONTS BUDGET AVAILABILITY 9D0 JS OK | rpVisionEsc(cameraReason) | offline distinct | server reason | two entrypoints');
