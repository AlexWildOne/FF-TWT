    public static function registerAutoload(): void {
        if (self::$autoloadRegistered) return;
        spl_autoload_register([self::class, 'autoload'], true, true);
        self::$autoloadRegistered = true;
    }

    public static function autoload(string $class): void {
        $class = ltrim($class, '\\');
        if (isset(self::$classMap[$class])) {
            self::requireFile(self::$classMap[$class]);
            return;
        }

        $prefix = 'RoutesPro\\';
        if (strncmp($class, $prefix, strlen($prefix)) !== 0) return;
        $relative = substr($class, strlen($prefix));
        if ($relative === '' || strpos($relative, '..') !== false) return;
        $relativePath = 'src/' . str_replace('\\', '/', $relative) . '.php';
        self::requireFile($relativePath);
    }

    public static function requireBootstrapFiles(): void {
        foreach (self::bootstrapFiles() as $relativePath) {
            self::requireFile($relativePath);
        }
    }

